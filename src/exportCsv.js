import ExcelJS from 'exceljs';

// Turns recent reservations into a downloadable, formatted Excel report.
// Uses `reservations` (amount, createdAt, driverId, lotId, status) rather
// than walletTransactions — reservations.amount is the field we've directly
// confirmed exists; swap the source here if you'd rather report off
// walletTransactions once its fields are confirmed too.
export async function exportRevenueCsv(
  reservations,
  filename = 'parkiti-revenue.xlsx',
  generatedBy = '',
  stats = {}, // { guardsOnline, guardsTotal, driversTotal, driversActive }
) {
  const workbook = new ExcelJS.Workbook();
  workbook.creator = 'Parkiti';
  workbook.created = new Date();

  const sheet = workbook.addWorksheet('Revenue', {
    views: [{ state: 'frozen', ySplit: 9 }], // freeze header rows while scrolling
  });

  sheet.columns = [
    { key: 'date', width: 12 },
    { key: 'time', width: 10 },
    { key: 'amount', width: 14 },
    { key: 'status', width: 12 },
    { key: 'driverName', width: 18 },
    { key: 'lotName', width: 26 },
  ];

  const totalAmount = reservations.reduce(
    (sum, r) => sum + (Math.abs(Number(r.amount)) || 0),
    0,
  );

  // --- Title band ---
  sheet.mergeCells('A1:F1');
  const titleCell = sheet.getCell('A1');
  titleCell.value = 'Parkiti — Revenue Report';
  titleCell.font = { size: 16, bold: true, color: { argb: 'FFFFFFFF' } };
  titleCell.alignment = { vertical: 'middle', horizontal: 'left' };
  sheet.getRow(1).height = 28;
  sheet.getRow(1).eachCell((c) => {
    c.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF1F1F23' } };
  });

  // --- Metadata ---
  sheet.getCell('A2').value = `Generated by: ${generatedBy || 'Admin'}`;
  sheet.getCell('A3').value = `Generated on: ${new Date().toLocaleString('fr-FR')}`;
  sheet.getCell('A4').value = `Total records: ${reservations.length}`;
  sheet.getCell('A5').value = `Total amount (MAD): ${totalAmount.toFixed(2)}`;
  sheet.getCell('A6').value = `Guards online: ${stats.guardsOnline ?? '—'} / ${stats.guardsTotal ?? '—'}`;
  sheet.getCell('A7').value = `Drivers active: ${stats.driversActive ?? '—'} / ${stats.driversTotal ?? '—'}`;
  ['A2', 'A3', 'A4', 'A5', 'A6', 'A7'].forEach((ref) => {
    sheet.getCell(ref).font = { italic: true, color: { argb: 'FF888888' } };
  });

  // --- Table header (row 9) ---
  const headerRow = sheet.getRow(9);
  headerRow.values = ['Date', 'Time', 'Amount (MAD)', 'Status', 'Driver', 'Lot'];
  headerRow.eachCell((cell) => {
    cell.font = { bold: true, color: { argb: 'FFFFFFFF' } };
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF3A3A40' } };
    cell.alignment = { vertical: 'middle', horizontal: 'center' };
    cell.border = { bottom: { style: 'thin', color: { argb: 'FF555555' } } };
  });

  // --- Data rows ---
  reservations.forEach((r) => {
    const d = r.createdAt?.toDate ? r.createdAt.toDate() : null;
    const row = sheet.addRow({
      date: d ? d.toISOString().slice(0, 10) : '',
      time: d ? d.toTimeString().slice(0, 8) : '',
      amount: Math.abs(Number(r.amount) || 0),
      status: r.status || '',
      driverName: r.driverName || '',
      lotName: r.lotName || '',
    });
    row.getCell('amount').numFmt = '#,##0.00';
    row.eachCell((cell) => {
      cell.border = { bottom: { style: 'hair', color: { argb: 'FFE5E5E5' } } };
    });
  });

  // --- Total row ---
  const totalRow = sheet.addRow({ status: 'TOTAL', amount: totalAmount });
  totalRow.font = { bold: true };
  totalRow.getCell('amount').numFmt = '#,##0.00';
  totalRow.eachCell((cell) => {
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFF0F0F0' } };
    cell.border = { top: { style: 'double', color: { argb: 'FF333333' } } };
  });

  const buffer = await workbook.xlsx.writeBuffer();
  const blob = new Blob([buffer], {
    type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
  });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}